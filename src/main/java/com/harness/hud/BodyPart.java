package com.harness.hud;

import java.util.HashMap;
import java.util.List;
import java.util.Map;

/**
 * Словарь «часть тела Терминатора → инструмент агента».
 *
 * <p>Ключ — <b>имя инструмента</b>, то, под которым его знает модель ({@code Read},
 * {@code Grep}, {@code Bash}), а не имя Java-класса. Имя класса — деталь реализации:
 * переименуй {@code FileReadTool}, и словарь бы молча перестал работать. Имя
 * инструмента — часть протокола, оно закреплено тестами и уходит в промпт.
 * В оригинале оба словаря такого рода тоже ключуются на имени инструмента
 * и сравнивают на точное равенство.
 *
 * <p>Имена перечислены только у тех частей, за которыми стоят инструменты.
 * За остальными стоит один конкретный бин, и что написать в скобках, {@link Hud}
 * решает сам. Смысл каждой части — в комментарии рядом: на экран он не попадает,
 * это словарь для нас, а не для зрителя.
 *
 * <p><b>Единственное место во всём проекте, где живёт эта связь.</b> Ядро агента
 * называет себя техническими именами, а во что это превращается на экране —
 * решается здесь.
 *
 * <p>Убрать пакет {@code hud} целиком — агент продолжит работать как ни в чём не бывало.
 * Это и есть проверка на то, что презентация отделена от логики.
 *
 * <p>Обратите внимание: самого {@link Hud} в этом словаре нет. Монитор — не орган.
 * Терминатор не перестанет быть Терминатором, если отключить экран, на который
 * смотрит создатель. Орган, который появляется в уроке 2, — это
 * {@link #DIAGNOSTIC_BUS}, то есть {@code agent.event}: шина, по которой машина
 * рапортует о себе. Монитор к ней подключён, но шина живёт и без него.
 *
 * <p>Словарь полон с самого начала: {@link #ARMAMENT}, {@link #COMMS_CHANNEL} и прочие
 * объявлены до того, как появятся соответствующие инструменты. Строка в boot-логе
 * возникает тогда, когда в контексте появляется бин, а не тогда, когда мы допишем
 * сюда константу.
 */
enum BodyPart {

    POWER_CELL("ЭНЕРГОЯЧЕЙКА"),                            // питание: контекст Spring поднялся
    NEUROPROCESSOR("НЕЙРОПРОЦЕССОР"),                      // чем машина думает: языковая модель
    MEMORY_BANK("БЛОК ПАМЯТИ"),                            // что она помнит: системный промпт и история, с урока 9 — их сжатие
    DIAGNOSTIC_BUS("ДИАГНОСТИЧЕСКИЙ КОНТУР"),              // чем рапортует о себе: события хода
    OPTICAL_SENSORS("ОПТИЧЕСКИЕ СЕНСОРЫ", "Read", "Grep"), // чтение кода
    TOOL_BUS("ИНСТРУМЕНТАЛЬНАЯ ШИНА"),                     // реестр инструментов
    CHASSIS("ШАССИ", "Glob"),                              // навигация по репозиторию
    MANIPULATORS("МАНИПУЛЯТОРЫ", "Edit", "Write"),         // редактирование файлов
    SKYNET_DATABASE("БАЗА ДАННЫХ SKYNET"),                 // знание о проекте: откуда берётся системный промпт
    ARMAMENT("ВООРУЖЕНИЕ", "Bash"),                        // деструктивные операции
    TACTICAL_PROCESSOR("ТАКТИЧЕСКИЙ ПРОЦЕССОР", "TodoWrite"), // планирование
    REINFORCEMENTS("ЗВЕНО ПОДКРЕПЛЕНИЯ", "Task"),          // субагенты
    COMMS_CHANNEL("КАНАЛ СВЯЗИ"),                          // диалог с пользователем

    /** Запасной вариант: инструмент есть, а в словаре его забыли. Лучше показать, чем скрыть. */
    UNKNOWN_MODULE("НЕОПОЗНАННЫЙ МОДУЛЬ");

    /**
     * Обратный индекс «имя инструмента → часть тела». Строится один раз при загрузке
     * класса, и там же ловится единственная ошибка, которую можно допустить в словаре
     * выше: один инструмент, заявленный двумя частями тела. Тогда приложение не
     * поднимется вовсе — вместо того чтобы показать на экране случайную из двух.
     */
    private static final Map<String, BodyPart> BY_TOOL_NAME = indexToolNames();

    private final String displayName;
    private final List<String> toolNames;

    BodyPart(String displayName, String... toolNames) {
        this.displayName = displayName;
        this.toolNames = List.of(toolNames);
    }

    String displayName() {
        return displayName;
    }

    /**
     * Часть тела, за которой стоит инструмент с таким именем.
     *
     * <p>Сравнение точное. Никаких «если в имени есть Write, значит манипуляторы»:
     * {@code TodoWrite} тогда уехал бы в манипуляторы вместо тактического процессора,
     * и правильность держалась бы на порядке проверок, невидимом в самом словаре.
     *
     * <p>Незнакомое имя — это {@link #UNKNOWN_MODULE}: инструмент виден на экране
     * как неопознанный, а не исчезает из boot-лога молча.
     */
    static BodyPart forToolName(String toolName) {
        return BY_TOOL_NAME.getOrDefault(toolName, UNKNOWN_MODULE);
    }

    private static Map<String, BodyPart> indexToolNames() {
        Map<String, BodyPart> index = new HashMap<>();
        for (BodyPart part : values()) {
            for (String toolName : part.toolNames) {
                BodyPart alreadyClaimed = index.put(toolName, part);
                if (alreadyClaimed != null) {
                    throw new IllegalStateException("инструмент %s заявлен дважды: %s и %s"
                            .formatted(toolName, alreadyClaimed, part));
                }
            }
        }
        return Map.copyOf(index);
    }
}
